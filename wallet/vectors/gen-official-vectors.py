#!/usr/bin/env python3
"""Turn the official test-vector files into wallet/vectors/official_vectors_data.h.

The vectors are not typed in by hand.  This script reads files fetched from
the repositories named below at fixed commits and writes them out as C tables,
recording the commit and the SHA-256 of every file it read.

usage: gen-official-vectors.py SRC_DIR OUT_FILE

SRC_DIR must hold (fetch with fetch-official-vectors.sh):
  bip-0032.mediawiki, bip-0086.mediawiki, bip-0350.mediawiki,
  wallet-test-vectors.json (bip-0341/), bip39-vectors.json, SOURCES
"""
import hashlib
import json
import os
import re
import sys

src, out_path = sys.argv[1], sys.argv[2]

FILES = {
    "bip-0032.mediawiki": "bips",
    "bip-0086.mediawiki": "bips",
    "bip-0350.mediawiki": "bips",
    "wallet-test-vectors.json": "bips",
    "bip39-vectors.json": "python-mnemonic",
}
URLS = {
    "bip-0032.mediawiki": "https://github.com/bitcoin/bips/blob/%s/bip-0032.mediawiki",
    "bip-0086.mediawiki": "https://github.com/bitcoin/bips/blob/%s/bip-0086.mediawiki",
    "bip-0350.mediawiki": "https://github.com/bitcoin/bips/blob/%s/bip-0350.mediawiki",
    "wallet-test-vectors.json": "https://github.com/bitcoin/bips/blob/%s/bip-0341/wallet-test-vectors.json",
    "bip39-vectors.json": "https://github.com/trezor/python-mnemonic/blob/%s/vectors.json",
}

commits = {}
for line in open(os.path.join(src, "SOURCES")):
    name, commit = line.split()
    commits[name] = commit


def read(name):
    data = open(os.path.join(src, name), "rb").read()
    return data.decode("utf-8"), hashlib.sha256(data).hexdigest()


def cstr(s):
    """A C string literal for s (a str of code points below 256)."""
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "?":
            out.append("\\?")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append('\\%03o' % o)
    return '"' + "".join(out) + '"'


lines = []
emit = lines.append
emit("/* GENERATED by wallet/vectors/gen-official-vectors.py.  Do not edit.")
emit(" *")
emit(" * Official test vectors, copied by script from these files:")
shas = {}
texts = {}
for name in FILES:
    texts[name], shas[name] = read(name)
    emit(" *   " + URLS[name] % commits[FILES[name]])
    emit(" *     sha256 " + shas[name])
emit(" * BIP 39 does not carry its vectors itself; its \"Test vectors\" section points to")
emit(" * the python-mnemonic file above.")
emit(" */")
emit("#ifndef GZW_OFFICIAL_VECTORS_DATA_H")
emit("#define GZW_OFFICIAL_VECTORS_DATA_H")
emit("")

# ---- BIP 39 ---------------------------------------------------------------
v39 = json.loads(texts["bip39-vectors.json"])["english"]
assert len(v39) == 24
emit("/* BIP 39: entropy, phrase, seed (passphrase \"TREZOR\"), master xprv. */")
emit("struct gzv_bip39 { const char *entropy_hex, *phrase, *seed_hex, *xprv; };")
emit("static const struct gzv_bip39 GZV_BIP39[] = {")
for ent, phrase, seed, xprv in v39:
    emit("    {%s,\n     %s,\n     %s,\n     %s}," % (cstr(ent), cstr(phrase), cstr(seed), cstr(xprv)))
emit("};")
emit("")

# ---- BIP 32 ---------------------------------------------------------------
t32 = texts["bip-0032.mediawiki"]
t32 = t32[t32.index("==Test Vectors=="):t32.index("==Acknowledgements==")]
rows = []
vec = None
seed = None
chain = None
pub = None
invalid = []
for line in t32.splitlines():
    m = re.match(r"===Test vector (\d+)===", line)
    if m:
        vec = int(m.group(1))
        continue
    m = re.match(r"Seed \(hex\): ([0-9a-f]+)$", line)
    if m:
        seed = m.group(1)
        continue
    m = re.match(r"\* Chain (m.*)$", line)
    if m:
        chain = m.group(1).replace("<sub>H</sub>", "'").strip()
        continue
    m = re.match(r"\*\* ext pub: (\S+)$", line)
    if m:
        pub = m.group(1)
        continue
    m = re.match(r"\*\* ext prv: (\S+)$", line)
    if m:
        rows.append((vec, seed, chain, pub, m.group(1)))
        continue
    m = re.match(r"\* ([1-9A-HJ-NP-Za-km-z]{100,}) \((.*)\)$", line)
    if m:
        assert vec == 5
        invalid.append((m.group(1), m.group(2)))
assert [sum(1 for r in rows if r[0] == v) for v in (1, 2, 3, 4)] == [6, 6, 2, 3], rows
assert len(invalid) == 16
emit("/* BIP 32 test vectors 1 to 4: every chain with its extended keys. */")
emit("struct gzv_bip32 { int vector; const char *seed_hex, *path, *xpub, *xprv; };")
emit("static const struct gzv_bip32 GZV_BIP32[] = {")
for r in rows:
    emit("    {%d, %s, %s,\n     %s,\n     %s}," % (r[0], cstr(r[1]), cstr(r[2]), cstr(r[3]), cstr(r[4])))
emit("};")
emit("")
emit("/* BIP 32 test vector 5: extended keys that must be refused. */")
emit("struct gzv_bip32_invalid { const char *key, *reason; };")
emit("static const struct gzv_bip32_invalid GZV_BIP32_INVALID[] = {")
for k, why in invalid:
    emit("    {%s,\n     %s}," % (cstr(k), cstr(why)))
emit("};")
emit("")

# ---- BIP 86 ---------------------------------------------------------------
t86 = texts["bip-0086.mediawiki"]
t86 = t86[t86.index("==Test vectors=="):]
t86 = t86[t86.index("<pre>") + 5:t86.index("</pre>")]
blocks = [b for b in t86.strip().split("\n\n")]
assert len(blocks) == 5


def fields(block):
    d = {}
    for line in block.splitlines():
        if line.startswith("//"):
            d["_comment"] = line
            continue
        k, v = line.split("=", 1)
        d[k.strip()] = v.strip()
    return d


root = fields(blocks[0])
acct = fields(blocks[1])
assert "m/86'/0'/0'" in acct["_comment"]
emit("/* BIP 86 test vectors. */")
emit("static const char GZV_BIP86_PHRASE[] = %s;" % cstr(root["mnemonic"]))
emit("static const char GZV_BIP86_ROOT_XPRV[] = %s;" % cstr(root["rootpriv"]))
emit("static const char GZV_BIP86_ROOT_XPUB[] = %s;" % cstr(root["rootpub"]))
emit("static const char GZV_BIP86_ACCOUNT_XPRV[] = %s;" % cstr(acct["xprv"]))
emit("static const char GZV_BIP86_ACCOUNT_XPUB[] = %s;" % cstr(acct["xpub"]))
emit("struct gzv_bip86 { const char *path, *xprv, *xpub, *internal_key, *output_key, *script_pubkey, *address; };")
emit("static const struct gzv_bip86 GZV_BIP86[] = {")
for b in blocks[2:]:
    f = fields(b)
    path = re.search(r"= (m/\S+)$", f["_comment"]).group(1)
    emit("    {%s,\n     %s,\n     %s,\n     %s,\n     %s,\n     %s,\n     %s}," % (
        cstr(path), cstr(f["xprv"]), cstr(f["xpub"]), cstr(f["internal_key"]),
        cstr(f["output_key"]), cstr(f["scriptPubKey"]), cstr(f["address"])))
emit("};")
emit("")

# ---- BIP 350 --------------------------------------------------------------
t350 = texts["bip-0350.mediawiki"]
a = t350.index("===Test vectors for Bech32m===")
b = t350.index("===Test vectors for v0-v16 native segregated witness addresses===")
c = t350.index("==Appendix: checksum design")
gen, seg = t350[a:b], t350[b:c]
g_valid_txt, g_invalid_txt = gen.split("The following string are not valid Bech32m")
g_valid = re.findall(r"^\* <tt>(.*)</tt>$", g_valid_txt, re.M)
g_invalid = []
for line in g_invalid_txt.splitlines():
    m = re.match(r"\* (?:0x([0-9A-F]{2}) \+ )?<tt>(.*)</tt>: (.*)$", line)
    if m:
        prefix = chr(int(m.group(1), 16)) if m.group(1) else ""
        g_invalid.append((prefix + m.group(2), m.group(3)))
assert len(g_valid) == 7 and len(g_invalid) == 14, (g_valid, g_invalid)
s_valid_txt, s_invalid_txt = seg.split("The following list gives invalid segwit addresses")
s_valid = re.findall(r"^\* <tt>(.*)</tt>: <tt>([0-9a-f]+)</tt>$", s_valid_txt, re.M)
s_invalid = re.findall(r"^\* <tt>(.*)</tt>: (.*)$", s_invalid_txt, re.M)
assert len(s_valid) == 8 and len(s_invalid) == 15, (s_valid, s_invalid)
emit("/* BIP 350: valid Bech32m strings. */")
emit("static const char *const GZV_BECH32M_VALID[] = {")
for s in g_valid:
    emit("    %s," % cstr(s))
emit("};")
emit("/* BIP 350: strings that are not valid Bech32m, with the stated reason. */")
emit("struct gzv_reason { const char *str, *reason; };")
emit("static const struct gzv_reason GZV_BECH32M_INVALID[] = {")
for s, why in g_invalid:
    emit("    {%s, %s}," % (cstr(s), cstr(why)))
emit("};")
emit("/* BIP 350: valid segwit addresses and their scriptPubKey. */")
emit("struct gzv_segwit { const char *address, *script_pubkey; };")
emit("static const struct gzv_segwit GZV_SEGWIT_VALID[] = {")
for addr, spk in s_valid:
    emit("    {%s,\n     %s}," % (cstr(addr), cstr(spk)))
emit("};")
emit("/* BIP 350: invalid segwit addresses, with the stated reason. */")
emit("static const struct gzv_reason GZV_SEGWIT_INVALID[] = {")
for addr, why in s_invalid:
    emit("    {%s,\n     %s}," % (cstr(addr), cstr(why)))
emit("};")
emit("")

# ---- BIP 341 (key path only) ----------------------------------------------
w = json.loads(texts["wallet-test-vectors.json"])
spk = [x for x in w["scriptPubKey"] if x["given"]["scriptTree"] is None]
assert len(spk) == 1
emit("/* BIP 341 wallet vectors: the scriptPubKey case with no script tree. */")
emit("struct gzv_bip341_spk { const char *internal_key, *output_key, *script_pubkey, *address; };")
emit("static const struct gzv_bip341_spk GZV_BIP341_SPK[] = {")
for x in spk:
    assert x["intermediary"]["merkleRoot"] is None
    emit("    {%s,\n     %s,\n     %s,\n     %s}," % (
        cstr(x["given"]["internalPubkey"]), cstr(x["intermediary"]["tweakedPubkey"]),
        cstr(x["expected"]["scriptPubKey"]), cstr(x["expected"]["bip350Address"])))
emit("};")
kp = [x for x in w["keyPathSpending"][0]["inputSpending"] if x["given"]["merkleRoot"] is None]
assert len(kp) == 1
emit("/* BIP 341 wallet vectors: the key-path spend whose key has no script tree.")
emit("   The signature is the witness element without its trailing hash-type byte;")
emit("   the vectors were made with all-zero auxiliary randomness. */")
emit("struct gzv_bip341_keypath { const char *internal_privkey, *internal_pubkey, *tweaked_privkey, *sighash, *signature; };")
emit("static const struct gzv_bip341_keypath GZV_BIP341_KEYPATH[] = {")
for x in kp:
    wit = x["expected"]["witness"][0]
    assert len(wit) == 130 and x["given"]["hashType"] != 0
    emit("    {%s,\n     %s,\n     %s,\n     %s,\n     %s}," % (
        cstr(x["given"]["internalPrivkey"]), cstr(x["intermediary"]["internalPubkey"]),
        cstr(x["intermediary"]["tweakedPrivkey"]), cstr(x["intermediary"]["sigHash"]),
        cstr(wit[:128])))
emit("};")
emit("")
emit("#endif /* GZW_OFFICIAL_VECTORS_DATA_H */")

with open(out_path, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote %s: bip39=%d bip32=%d bip32-invalid=%d bip86=%d bech32m=%d+%d segwit=%d+%d bip341=%d+%d" % (
    out_path, len(v39), len(rows), len(invalid), len(blocks) - 2, len(g_valid),
    len(g_invalid), len(s_valid), len(s_invalid), len(spk), len(kp)))
