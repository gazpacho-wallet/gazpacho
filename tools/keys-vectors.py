#!/usr/bin/env python3
"""Test vectors for program/keys.c (docs/notes/keys.md), from tools/keys_ref.py.

    python3 -I tools/keys-vectors.py --header      # tests/program/keys_vectors.h
    python3 -I tools/keys-vectors.py --check FILE  # FILE equals what --header prints (CTest)
    VENV/bin/python -I tools/keys-vectors.py --embit
        # every vector recomputed with embit (an independent BIP 32, BIP 86 and
        # BIP 341 implementation; install it in a virtual environment, never
        # system-wide): exit 0 only if all agree. Run by hand on the build server.

THE KEYS HERE ARE TEST KEYS, derived from public test phrases (BIP 86's
"abandon ... about" and the all-zero entropy's "abandon ... art"). Never use
them for coins."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import keys_ref as R  # noqa: E402

SEEDS = [("about", R.ABOUT), ("art", R.ART)]
C_NET = {"signet": "GZW_NET_SIGNET", "testnet4": "GZW_NET_TESTNET4", "testnet": "GZW_NET_TESTNET",
         "regtest": "GZW_NET_REGTEST"}
EPOCHS = [0, 1, 0x2A5F3C11, 0x7FFFFFFF]
INDEXES = [0, 1, 2, 3, 0x7FFFFFFE, 0x7FFFFFFF]


def vectors():
    lob, hosts, wal = [], [], []
    for si, (_, phrase) in enumerate(SEEDS):
        seed = R.bip39_seed(phrase)
        for net in ("signet", "testnet4", "testnet", "regtest"):
            k, sec = R.host(seed, net)
            hosts.append((si, net, k, sec.to_bytes(32, "big"), R.ser33(R.mul(sec))))
        for net in ("signet", "testnet4"):
            for e in EPOCHS:
                for i in INDEXES:
                    if net == "testnet4" and (e, i) not in ((0, 1), (0, 2)):
                        continue
                    sec = R.lobby(seed, net, e, i)
                    lob.append((si, net, 0, e, i, sec.to_bytes(32, "big"), R.ser33(R.mul(sec))))
        for e in (0, 0x2A5F3C11):  # a host's own pairs (branch 2')
            for i in (1, 2, 3):
                sec = R.lobby(seed, "signet", e, i, host=True)
                lob.append((si, "signet", 1, e, i, sec.to_bytes(32, "big"), R.ser33(R.mul(sec))))
        for net in ("signet", "regtest"):
            for change, j in ((0, 0), (0, 1), (0, 0x7FFFFFFF), (1, 0)):
                wal.append((si, net, change, j, R.bip86(seed, net, change, j)[2]))
    return lob, hosts, wal


def header():
    R.selftest()
    lob, hosts, wal = vectors()
    out = ["/* Generated by tools/keys-vectors.py --header from tools/keys_ref.py: do not edit.",
           " * THE KEYS HERE ARE TEST KEYS, from public test phrases. Never use them for coins. */",
           "#ifndef GZP_KEYS_VECTORS_H", "#define GZP_KEYS_VECTORS_H", "",
           "static const char *const KV_SEED[] = {"]
    for name, phrase in SEEDS:
        out.append('    "%s", /* %s: "%s" */' % (R.bip39_seed(phrase).hex(), name, " ".join(phrase.split()[-2:])))
    out += ["};", "", "static const struct { int seed; gzw_network net; int host; uint32_t epoch, index; const char *sec, *pub; } KV_LOBBY[] = {"]
    for si, net, host, e, i, sec, pub in lob:
        out.append('    {%d, %s, %d, 0x%08xu, 0x%08xu, "%s", "%s"},' % (si, C_NET[net], host, e, i, sec.hex(), pub.hex()))
    out += ["};", "", "static const struct { int seed; gzw_network net; uint32_t k; const char *sec, *pub; } KV_HOST[] = {"]
    for si, net, k, sec, pub in hosts:
        out.append('    {%d, %s, %du, "%s", "%s"},' % (si, C_NET[net], k, sec.hex(), pub.hex()))
    out += ["};", "", "static const struct { int seed; gzw_network net; uint32_t change, j; const char *spk; } KV_WALLET[] = {"]
    for si, net, change, j, spk in wal:
        out.append('    {%d, %s, %du, 0x%08xu, "%s"},' % (si, C_NET[net], change, j, spk.hex()))
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def embit_check():
    from importlib.metadata import version
    from embit import bip32, bip39, script

    lob, hosts, wal = vectors()
    bad = 0

    def same(what, a, b):
        nonlocal bad
        if a != b:
            bad += 1
            print("DIFFER %s" % what)

    roots = [bip32.HDKey.from_seed(bip39.mnemonic_to_seed(p)) for _, p in SEEDS]
    for si, net, host, e, i, sec, pub in lob:
        k = roots[si].derive([R.PURPOSE | R.HARD, R.NET_LEVEL[net] | R.HARD, (2 if host else 0) | R.HARD, e | R.HARD,
                              i | R.HARD])
        same("lobby %d %s host=%d %x %x secret" % (si, net, host, e, i), k.key.secret, sec)
        same("lobby %d %s host=%d %x %x pub" % (si, net, host, e, i), k.key.sec(), pub)
    for si, net, kk, sec, pub in hosts:
        k = roots[si].derive([R.PURPOSE | R.HARD, R.NET_LEVEL[net] | R.HARD, 1 | R.HARD, kk | R.HARD])
        same("host %d %s" % (si, net), (k.key.secret, k.key.sec()), (sec, pub))
    for si, net, change, j, spk in wal:
        acct = roots[si].derive([86 | R.HARD, 1 | R.HARD, R.HARD]).to_public()  # public below the account
        same("wallet %d %s %d/%d" % (si, net, change, j), script.p2tr(acct.derive([change, j])).data, spk)
    n = len(lob) + len(hosts) + len(wal)
    print("embit %s: %d vectors, %d differ" % (version("embit"), n, bad))
    return 1 if bad else 0


def main():
    if sys.argv[1:] == ["--header"]:
        sys.stdout.write(header())
        return 0
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        with open(sys.argv[2]) as f:
            ok = f.read() == header()
        print("keys vectors: %s" % ("the header matches the reference" if ok else "the header DIFFERS from the reference"))
        return 0 if ok else 1
    if sys.argv[1:] == ["--embit"]:
        R.selftest()
        return embit_check()
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
