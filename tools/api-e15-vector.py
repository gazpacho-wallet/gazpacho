#!/usr/bin/env python3
"""Writes tests/api/e15_vector.h from vector E15 of tools/spec-vectors.py
(spec/local-api.md 7.4): the request digest's canonical bytes and SHA-256.

    python3 -I tools/api-e15-vector.py > tests/api/e15_vector.h

Takes the JCS code and the E15 body from spec-vectors.py itself (the block
between `def jcs` and the E15 print), so the C test checks the same bytes the
specification prints. --check compares with the committed header instead.
Standard library only."""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def header():
    text = open(os.path.join(ROOT, "tools", "spec-vectors.py"), encoding="utf-8").read()
    start = text.index("def jcs(v):")
    end = text.index('print("\\n== vector E15')
    ns = {"hashlib": hashlib}
    exec(compile(text[start:end], "spec-vectors.py (E15 block)", "exec"), ns)
    canon = ns["_jcs"].encode("utf-8")
    digest = ns["request_digest"](ns["JCS_BODY"]).hex()
    out = []
    for b in canon:
        if b in (0x22, 0x5c):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7f:
            out.append(chr(b))
        else:
            out.append("\\x%02x\" \"" % b)
    lines = ["/* Generated by tools/api-e15-vector.py from tools/spec-vectors.py: vector E15",
             " * (spec/local-api.md 7.4), the canonical bytes and the request digest. */",
             "#define E15_CANONICAL \"%s\"" % "".join(out),
             "#define E15_DIGEST \"%s\"" % digest, ""]
    return "\n".join(lines)


def main():
    h = header()
    if sys.argv[1:] == ["--check"]:
        cur = open(os.path.join(ROOT, "tests", "api", "e15_vector.h"), encoding="utf-8").read()
        if cur != h:
            print("FAIL: tests/api/e15_vector.h differs from tools/spec-vectors.py's E15")
            return 1
        print("PASS: tests/api/e15_vector.h matches vector E15")
        return 0
    sys.stdout.write(h)
    return 0


if __name__ == "__main__":
    sys.exit(main())
