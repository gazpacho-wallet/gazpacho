#!/usr/bin/env python3
"""Generate ports/storage/crypto/sc_wordlist.c from the EFF large word list.

    python3 -I tools/gen-eff-wordlist.py eff_large_wordlist.txt > ports/storage/crypto/sc_wordlist.c

Source: Electronic Frontier Foundation, "EFF's New Wordlists for Random
Passphrases" (2016), https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt
Licence: Creative Commons Attribution 3.0 United States (CC BY 3.0 US),
https://creativecommons.org/licenses/by/3.0/us/ ; attribution kept in the
generated file. It is not the BIP 39 list (spec/storage-encryption.md 14).
The input file is pinned by SHA-256 below; the generated file is committed and
its word digest is checked by the storage tests. Standard library only.
"""
import hashlib
import sys

PINNED = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"

data = open(sys.argv[1], "rb").read()
if hashlib.sha256(data).hexdigest() != PINNED:
    sys.exit("eff_large_wordlist.txt: SHA-256 differs from the pinned value")
words = []
for i, line in enumerate(data.decode("ascii").splitlines()):
    dice, word = line.split("\t")
    assert len(dice) == 5 and set(dice) <= set("123456")
    assert word.isascii() and word.replace("-", "").isalpha() and word == word.lower()
    words.append(word)
assert len(words) == 7776 and len(set(words)) == 7776
digest = hashlib.sha256("\n".join(words).encode()).hexdigest()
print("/* GENERATED by tools/gen-eff-wordlist.py; do not edit.")
print(" *")
print(" * The EFF large word list (7,776 words), Electronic Frontier Foundation, 2016,")
print(" * https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt")
print(" * (SHA-256 of that file: %s)." % PINNED)
print(" * Licensed under Creative Commons Attribution 3.0 United States")
print(" * (CC BY 3.0 US), https://creativecommons.org/licenses/by/3.0/us/ .")
print(" * Used for the generated six-word passphrase (spec/storage-encryption.md 4.1, 14).")
print(" * SHA-256 of the words joined by newlines: %s */" % digest)
print('#include "sc_pass.h"')
print()
print("const char *const gz_sc_eff_words[GZ_SC_EFF_WORDS] = {")
for i in range(0, len(words), 6):
    print("    " + " ".join('"%s",' % w for w in words[i:i + 6]))
print("};")
print("/* longest word: %d characters */" % max(len(w) for w in words))
