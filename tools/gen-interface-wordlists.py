#!/usr/bin/env python3
"""Write the interface's two word lists from the program's own copies.

    python3 -I tools/gen-interface-wordlists.py            # rewrite web/js/bip39.js and web/js/eff.js
    python3 -I tools/gen-interface-wordlists.py --check    # fail if they differ

web/js/bip39.js: the BIP 39 English list (2,048 words), from
core/superscalar/src/bip39_wordlist.h. The check and restore screens offer
matching words from it, in the page, instead of the browser's own suggestions
(spec/local-api.md 12.7).

web/js/eff.js: the EFF large word list (7,776 words), from
ports/storage/crypto/sc_wordlist.c. The first-run screen makes the suggested
six-word passphrase from it (spec/storage-encryption.md 14).

The generated files are committed, so the interface needs no build step; the
test tests/web/check_static.py runs this with --check. Standard library only.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORD = re.compile(r'"([a-z-]+)"')

LISTS = [
    ("core/superscalar/src/bip39_wordlist.h", "web/js/bip39.js", "bip39", 2048,
     "The BIP 39 English word list (2,048 words), as in core/superscalar/src/bip39_wordlist.h.\n"
     "   Used only to offer matching words while the 24 words are typed (the check and\n"
     "   restore screens). GENERATED by tools/gen-interface-wordlists.py; do not edit."),
    ("ports/storage/crypto/sc_wordlist.c", "web/js/eff.js", "effWords", 7776,
     "The EFF large word list (7,776 words), Electronic Frontier Foundation, 2016,\n"
     "   licensed under Creative Commons Attribution 3.0 United States (CC BY 3.0 US);\n"
     "   source and licence addresses are in ports/storage/crypto/sc_wordlist.c, which\n"
     "   this file is made from. Used for the suggested six-word passphrase. It is not\n"
     "   the 24-word list. GENERATED by tools/gen-interface-wordlists.py; do not edit."),
]


def render(src, name, count, note):
    text = open(os.path.join(ROOT, src), encoding="utf-8").read()
    words = WORD.findall(text)
    if len(words) != count or len(set(words)) != count:
        sys.exit("%s: expected %d distinct words, found %d" % (src, count, len(words)))
    lines = ["// SPDX-License-Identifier: MIT", "/* " + note + " */", "(function () {", '  "use strict";',
             "  window.gz." + name + " = ("]
    for i in range(0, count, 10):
        lines.append('    "' + " ".join(words[i:i + 10]) + (' " +' if i + 10 < count else '"'))
    lines += ['  ).split(" ");', "})();", ""]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    bad = 0
    for src, out, name, count, note in LISTS:
        want = render(src, name, count, note)
        path = os.path.join(ROOT, out)
        if check:
            have = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else ""
            if have != want:
                print("FAIL: %s is not what tools/gen-interface-wordlists.py writes" % out)
                bad = 1
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(want)
            print("wrote %s (%d words)" % (out, count))
    return bad


if __name__ == "__main__":
    sys.exit(main())
